export type PromptParts = { key: string; label: string; text: string }[];

/** 조립 결과를 조각 단위로 돌려준다 — 실험실 화면이 "어느 문장이 왜 들어갔는지"를 보여 준다. */
export function assemblePrompt(mods: ToolManifest[], denied: { id: string; title_ko: string }[] = []): PromptParts {
  const parts: PromptParts = [];
  COMMON_HEADER.forEach((t, i) => parts.push({ key: `common.${i}`, label: "공통 머리말", text: t }));
  if (mods.some((m) => m.erp)) parts.push({ key: "erp", label: "ERP 모듈 있음", text: ERP_HINT });
  const doms = [...new Set(mods.map((m) => m.domain))];
  for (const d of doms) (DOMAIN_HINTS[d] || []).forEach((t, i) => parts.push({ key: `domain.${d}.${i}`, label: `도메인 · ${d}`, text: t }));
  for (const m of mods) if (m.prompt_hint) parts.push({ key: `tool.${m.id}`, label: `모듈 · ${m.id}`, text: m.prompt_hint });
  // [신규] 권한별 숨김(perm_filter=hide)일 때 — 모델이 "그런 기능은 없다"고 오답하지 않게 이름만 알린다(§2-5 말미).
  if (denied.length) {
    parts.push({ key: "denied", label: "권한 밖 기능(이름만)", text:
      `[신규] 다음 기능은 이 사용자에게 권한이 없어 도구를 제공하지 않습니다: ${denied.map((d) => d.title_ko).join(", ")}. ` +
      "사용자가 이 기능을 물으면 데이터를 지어내지 말고, 권한이 없다는 사실과 포털 관리자에게 해당 ERP 모듈 권한을 요청하는 방법을 안내하세요." });
  }
  return parts;
}
export const joinPrompt = (p: PromptParts) => p.map((x) => x.text).join(" ");
